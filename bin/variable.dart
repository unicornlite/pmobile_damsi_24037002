void main(){
  //Tanpa Variable
  print('Damsi');
  print('Damsi');
  print('Damsi');
  print('Damsi');

  //Variable
  String name;
  name = 'Damsi';
  print(name);
  print(name);
  print(name);
  print(name);

  //Deklarasi Variable Langsung
  String name1 = 'Damsi';
  print(name1);
  print(name1);
  print(name1);
  print(name1);
  print(name1);

  //Kata Kunci var
  var name2 = 'Damsi';
  print(name2);
  print(name2);
  print(name2);
  print(name2);

  //Kata Kunci final
  var firstName = 'Damsi';
  final lastName = 'Adam'; 
  print(firstName);
  print(lastName);
}