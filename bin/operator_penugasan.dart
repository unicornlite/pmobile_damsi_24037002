void main() {

  //Operator Penugasan
  var a = 10;
  a += 10; // a = a + 10
  a -= 10; // a = a - 10
  a *= 10; // a = a * 10
  a ~/= 10; // a = a ~/ 10
  a %= 10; // a = a % 10
  print(a);

  //Increment dan Decrement
  var b = 5;
  b++; // b = b + 1
  b--; // b = b - 1
  --b; // b = b - 1
  ++b; // b = b + 1
  print(b);
}